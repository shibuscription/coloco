const createChromaticPoint = (row: ChromaticSourceRow): ChromaticPccsPoint => {
  const parsed = parsePccsNotation(row.pccsNotation);
  const hue = pccsHueMapByIndex24.get(parsed.hueIndex24);

  if (!hue) {
    throw new Error(`Unknown hueIndex24: ${parsed.hueIndex24}`);
  }

  return {
    id: `${row.toneCode}-${parsed.hueIndex24}`,
    kind: "chromatic",
    toneCode: row.toneCode,
    toneNameJa: toneNamesJa[row.toneCode],
    hueIndex24: hue.hueIndex24,
    hueCode24: hue.hueCode24,
    hueNameJa: hue.hueNameJa,
    hueIndex12: getRepresentativeIndex12(hue.hueIndex24),
    isRepresentative12: hue.isRepresentative12,
    pccsNotation: parsed.normalizedNotation,
    pccsLightness: parsed.pccsLightness,
    pccsSaturation: parsed.pccsSaturation,
    munsellNotation: row.munsellNotation,
    hex: row.hex,
    rgb: row.rgb,
  };
};

export const pccsPoints: ChromaticPccsPoint[] = chromaticSourceRows.map(createChromaticPoint);
